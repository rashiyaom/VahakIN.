import { authenticateDemo } from "./demo-auth";
import { test, expect } from "@playwright/test";
const origin=process.env.VAHAKIN_TEST_URL||"http://localhost:3000";
test("theme persists across public pages and RTO financial dashboards",async({page})=>{
 const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
 await page.emulateMedia({colorScheme:"light"});await page.goto("/");
 await expect(page.locator("html")).toHaveAttribute("data-theme","light");
 await expect(page.locator(".hero-image-light")).toHaveCSS("opacity","1");
 await expect(page.locator(".hero-image-dark")).toHaveCSS("opacity","0");
 expect(await page.locator(".hero-image-dark").evaluate(el=>parseFloat(getComputedStyle(el).transitionDuration))).toBeGreaterThan(0);
 await page.screenshot({path:"/tmp/vahakin-hero-light.png"});
 await page.getByRole("button",{name:"Switch to dark mode"}).click();
 await expect(page.locator("html")).toHaveAttribute("data-theme","dark");
 await expect(page.locator(".hero-image-dark")).toHaveCSS("opacity","1");
 await expect(page.locator(".stat-image .theme-art-dark")).toHaveCSS("opacity","1");
 await expect(page.locator(".people-visual .theme-art-dark")).toHaveCSS("opacity","1");
 await page.screenshot({path:"/tmp/vahakin-hero-dark.png"});
 expect(await page.evaluate(()=>localStorage.getItem("vahakin-theme"))).toBe("dark");
 await page.reload();await expect(page.locator("html")).toHaveAttribute("data-theme","dark");
 await page.locator("#about").scrollIntoViewIfNeeded();await expect(page.locator(".stat-card").first()).toBeVisible();await expect(page.locator(".stat-card").last()).toHaveCSS("opacity","1");await expect(page.locator(".section-intro")).toHaveCSS("opacity","1");
 await page.screenshot({path:"/tmp/vahakin-home-dark.png"});
 await page.locator(".footer-panorama").scrollIntoViewIfNeeded();
 await expect(page.locator(".footer-panorama img")).toHaveCSS("opacity","1");
 await expect(page.locator(".footer-panorama img")).toHaveCSS("mix-blend-mode","normal");
 await page.locator(".footer-panorama").screenshot({path:"/tmp/vahakin-footer-dark.png"});
 await page.goto("/login/government");await expect(page.getByRole("button",{name:"Switch to light mode"})).toBeVisible();
 await authenticateDemo(page.request);
 await page.request.post("/api/session",{headers:{Origin:origin},data:{mode:"demo",accountId:"demo-rto"}});
 await page.goto("/gov");await expect(page.locator("html")).toHaveAttribute("data-theme","dark");
 await expect(page.locator(".reference-summary")).toBeVisible();await page.screenshot({path:"/tmp/vahakin-dashboard-dark.png"});
 await page.goto("/gov/compliance");await expect(page.locator(".tax-case-detail")).toBeVisible();
 await page.getByRole("button",{name:"Add finding",exact:true}).click();await expect(page.locator(".tax-action-dialog")).toBeVisible();await page.screenshot({path:"/tmp/vahakin-dialog-dark.png"});await page.keyboard.press("Escape");
 await page.setViewportSize({width:390,height:844});await page.reload();expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole("button",{name:"Switch to light mode"}).click();await expect(page.locator("html")).toHaveAttribute("data-theme","light");
 await page.goto("/");await expect(page.locator("html")).toHaveAttribute("data-theme","light");expect(errors).toEqual([]);
});
test("system dark preference and reduced motion work without a saved theme",async({page})=>{
 await page.emulateMedia({colorScheme:"dark",reducedMotion:"reduce"});await page.setViewportSize({width:390,height:844});await page.goto("/");
 await expect(page.locator("html")).toHaveAttribute("data-theme","dark");await expect(page.locator(".hero-copy h1")).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await expect(page.getByRole("button",{name:"Switch to light mode"})).toBeVisible();
});
