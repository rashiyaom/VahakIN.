import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(new URL('../apps/web/package.json',import.meta.url));
const {chromium}=require('@playwright/test');
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1400,height:1200},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(new URL('../deliverables/watch-ui/index.html',import.meta.url).href);
await page.getByRole('button',{name:'Location',exact:true}).first().click();
const map=page.locator('#map');const rect=await map.boundingBox();
const before=await page.locator('#mapimg').getAttribute('style');
await page.mouse.move(rect.x+170,rect.y+160);await page.mouse.down();await page.mouse.move(rect.x+290,rect.y+230,{steps:8});await page.mouse.up();
if(before===await page.locator('#mapimg').getAttribute('style'))throw Error('Map did not pan');
await page.getByRole('button',{name:'Recenter venue'}).click();
await page.getByRole('button',{name:'Test 5-second sleep'}).click();await page.waitForTimeout(5200);
if(!await page.locator('#sleep').isVisible())throw Error('Sleep timeout failed');
await page.getByRole('button',{name:'Move watch',exact:true}).click();
if(await page.locator('#sleep').isVisible())throw Error('Motion wake failed');
await page.getByRole('button',{name:'Test 5-second sleep'}).click();
await page.screenshot({path:fileURLToPath(new URL('../deliverables/watch-ui/studio-preview.png',import.meta.url)),fullPage:true});
await page.setViewportSize({width:390,height:844});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile horizontal overflow');
if(errors.length)throw Error(errors.join('\n'));
console.log('Preview passed: map drag/recenter, 5-second sleep, motion wake, mobile layout, no script errors.');
await browser.close();
